/**
 * Разбор того, что человек набрал в поле очков.
 *
 * За партию очки приходят кучками — 35 за одну взятку, 56 за другую, — и складывать
 * их в уме, держа телефон одной рукой, неудобно. Поэтому поле принимает не только
 * число, но и сумму: `35+56+12`. Минус тоже понимается: очки иногда снимают.
 *
 * Пробелы игнорируются целиком: на телефоне они появляются сами, от автозамены и
 * промахов по пробелу, и человек не должен из-за них видеть «не понял».
 */
export function parsePoints(input: string): number | null {
  const cleaned = input.replace(/\s+/g, '')
  if (cleaned === '') return null

  // Формула целиком, а не «первое похожее число»: половину строки принять нельзя —
  // «35+» это ещё не законченный ввод, и молча посчитать его за 35 значит записать
  // не то, что человек собирался.
  if (!/^[+-]?\d+([+-]\d+)*$/.test(cleaned)) return null

  const terms = cleaned.match(/[+-]?\d+/g)
  if (terms === null) return null

  return terms.reduce((sum, term) => sum + Number(term), 0)
}

/** Есть ли в наборе арифметика — то есть стоит ли показывать итог рядом с полем. */
export function looksLikeSum(input: string): boolean {
  return /\d[\s]*[+-]/.test(input)
}
